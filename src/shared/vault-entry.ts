/**
 * 隱私空間的隱密入口：在搜尋框打一段觸發字串，跳出獨立的密碼輸入畫面。
 *
 * 為什麼不直接把主密碼打進搜尋框（原本的做法）：搜尋框是明文顯示的，旁邊的人
 * 直接讀得到。那比「被人知道有隱私空間」嚴重得多 —— 密碼外洩不可挽回，對方
 * 之後隨時能開，而且目前還沒有備份出口。改成觸發字串之後，進搜尋框的只有
 * 觸發字串本身，密碼走真正的 `type="password"` 欄位，全程不經過搜尋狀態。
 *
 * 觸發字串可在設定頁調整。可調整同時也是**安全性的一部分**：預設值是公開的，
 * 知道預設值的人打一次就能看出這台機器有沒有隱私空間（跳出的是「解鎖」還是
 * 「建立」）。改成只有自己知道的字串，那個推測就無從下手。
 */
export const DEFAULT_VAULT_TRIGGER = '###';

/**
 * 主密碼的最短長度。
 *
 * 放在這裡是因為**有兩個地方在把關**：側邊欄的建立表單與設定頁的更改密碼表單。
 * 各寫一個 8 的話，改動時很容易只改到其中一邊 —— 而症狀是「建立時要 10 個字，
 * 改密碼時 8 個就過」，兩邊都沒有錯誤訊息。文案也會提到這個數字（「至少 $MIN$ 字」），
 * 所以它同時是規則與說明，更不該有兩份。
 */
export const MIN_PASSWORD_LENGTH = 8;

/**
 * 這串輸入是否正好等於觸發字串。
 *
 * 用完全相等而不是「開頭符合」：開頭符合會讓任何以觸發字串起頭的正常搜尋
 * 在打到一半時就把畫面叫出來。大小寫也不做寬鬆比對 —— 觸發字串可能被設成
 * 一般單字，寬鬆比對會讓普通搜尋意外命中。
 *
 * 觸發字串為空視為停用，避免設定被清空後每次輸入都跳畫面。
 */
export function matchesVaultTrigger(value: string, trigger: string): boolean {
  const needle = trigger.trim();
  return needle !== '' && value.trim() === needle;
}
